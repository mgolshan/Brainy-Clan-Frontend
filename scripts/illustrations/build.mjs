/**
 * Builds the category illustrations (run `npm run art:build`):
 *   src/ui/illustrations/categoryArt.generated.ts   slug -> SVG string (SvgXml), + the fallback
 *   assets/illustrations/_sheets/*.png              contact sheets for design review (git-ignored)
 * One scene per top-level category slug (backend categories.php), drawn with the Clan characters
 * (scripts/clan) in the same flat style; transparent background so card styles show through.
 * Uses @resvg/resvg-js (devDependency) for the sheets; nothing here ships in the app.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { Resvg } from '@resvg/resvg-js';

import { FALLBACK, SCENES } from './scenes.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const sheetDir = join(root, 'assets/illustrations/_sheets');
const tsOut = join(root, 'src/ui/illustrations/categoryArt.generated.ts');

const wrap = (body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">${body}</svg>`;
const art = Object.entries(SCENES).map(([slug, fn]) => ({ slug, svg: wrap(fn()) }));
const fallback = { slug: 'fallback', svg: wrap(FALLBACK()) };

for (const { slug, svg } of [...art, fallback]) {
  if (/\sid=|url\(#|NaN|undefined/.test(svg)) throw new Error(`${slug}: ids, NaN or undefined`);
}

mkdirSync(dirname(tsOut), { recursive: true });
const q = (svg) => JSON.stringify(svg.replace(/"/g, "'"));
writeFileSync(
  tsOut,
  [
    '// Generated by scripts/illustrations/build.mjs (`npm run art:build`). Do not edit by hand.',
    '',
    '/** Top-level category slug -> SVG markup (256² viewBox, transparent), for SvgXml. */',
    'export const CATEGORY_ART: Readonly<Record<string, string>> = {',
    ...art.map(({ slug, svg }) => `  ${JSON.stringify(slug)}: ${q(svg)},`),
    '};',
    '',
    '/** Ollie with a question mark: any slug without art. */',
    `export const FALLBACK_ART = ${q(fallback.svg)};`,
    '',
  ].join('\n'),
);

// --- contact sheets --------------------------------------------------------
mkdirSync(sheetDir, { recursive: true });
const inner = (svg) => svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
const items = [...art, fallback];

function sheet(name, cell, cards, bg) {
  const pad = Math.max(8, Math.round(cell * 0.12));
  const cols = items.length;
  const W = cols * (cell + pad) + pad;
  const H = cards.length * (cell + pad) + pad;
  let body = `<rect width="${W}" height="${H}" fill="${bg}"/>`;
  cards.forEach((card, r) =>
    items.forEach((item, c) => {
      const x = pad + c * (cell + pad);
      const y = pad + r * (cell + pad);
      body += `<rect x="${x}" y="${y}" width="${cell}" height="${cell}" rx="${cell * 0.16}" fill="${card}"/>`;
      // nested <svg> clips like the app's root SvgXml does (overflow below/right is hidden)
      body += `<svg x="${x}" y="${y}" width="${cell}" height="${cell}" viewBox="0 0 256 256">${inner(item.svg)}</svg>`;
    }),
  );
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">${body}</svg>`;
  writeFileSync(join(sheetDir, `${name}.png`), new Resvg(svg).render().asPng());
}

// Card colours roughly like the worlds: candy pink, jungle green, space navy, neon dark, glass.
const CARDS = ['#FFE3EE', '#DFF3D6', '#1E2547', '#14111F', '#EEF3FA'];
sheet('detail-200', 200, ['#FFF1E0'], '#FFFFFF');
sheet('cards-160', 160, CARDS, '#F6F3EE');
sheet('cards-96', 96, CARDS, '#F6F3EE');
sheet('cards-64', 64, CARDS, '#F6F3EE');

const kb = items.reduce((n, i) => n + i.svg.length, 0) / 1024;
console.log(
  `art: ${art.length} scenes + fallback, ${kb.toFixed(0)} KB of SVG, sheets in assets/illustrations/_sheets`,
);
