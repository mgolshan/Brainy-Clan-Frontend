/**
 * Builds the Clan avatars (run `npm run clan:build`):
 *   assets/clan/<key>.svg                   one SVG per avatar key (132)
 *   src/ui/avatars/clanSvgs.generated.ts    key -> SVG string (rendered with react-native-svg SvgXml)
 *   assets/clan/_sheets/*.png               contact sheets for design review (git-ignored)
 * Keys follow the API contract: `<species>` (the kid) or `<species>-<variant>`.
 * Uses @resvg/resvg-js (devDependency) for the sheets; nothing here ships in the app.
 */
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { Resvg } from '@resvg/resvg-js';

import { SPECIES } from './species.mjs';
import { compose, VARIANTS } from './variants.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const outDir = join(root, 'assets/clan');
const sheetDir = join(outDir, '_sheets');
const tsOut = join(root, 'src/ui/avatars/clanSvgs.generated.ts');

const keyOf = (species, v) => (v === 'kid' ? species : `${species}-${v}`);

mkdirSync(outDir, { recursive: true });
mkdirSync(sheetDir, { recursive: true });
for (const f of readdirSync(outDir)) if (f.endsWith('.svg')) rmSync(join(outDir, f));

const all = [];
SPECIES.forEach((spec, i) => {
  for (const v of VARIANTS) {
    const key = keyOf(spec.key, v);
    const svg = compose(spec, v, i);
    writeFileSync(join(outDir, `${key}.svg`), svg + '\n');
    all.push({ key, svg, species: spec.key, v });
  }
});

// --- TS module -------------------------------------------------------------
const lines = [
  '// Generated by scripts/clan/build.mjs (`npm run clan:build`). Do not edit by hand.',
  "import type { AvatarKey } from './keys';",
  '',
  '/** Avatar key -> SVG markup (256² viewBox), rendered with react-native-svg `SvgXml`. */',
  'export const CLAN_SVGS: Readonly<Record<AvatarKey, string>> = {',
  ...all.map(
    ({ key, svg }) => `  ${JSON.stringify(key)}: ${JSON.stringify(svg.replace(/"/g, "'"))},`,
  ),
  '};',
  '',
];
writeFileSync(tsOut, lines.join('\n'));

// --- contact sheets --------------------------------------------------------
const inner = (svg) => svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');

function sheet(name, rows, cell, bg, bubble) {
  const cols = Math.max(...rows.map((r) => r.length));
  const pad = Math.round(cell * 0.08);
  const W = cols * (cell + pad) + pad;
  const H = rows.length * (cell + pad) + pad;
  let body = `<rect width="${W}" height="${H}" fill="${bg}"/>`;
  rows.forEach((row, r) =>
    row.forEach((item, c) => {
      const x = pad + c * (cell + pad);
      const y = pad + r * (cell + pad);
      const s = cell / 256;
      body += `<clipPath id="k${r}_${c}"><circle cx="${x + cell / 2}" cy="${y + cell / 2}" r="${cell / 2}"/></clipPath>`;
      body += `<g clip-path="url(#k${r}_${c})"><circle cx="${x + cell / 2}" cy="${y + cell / 2}" r="${cell / 2}" fill="${bubble}"/>`;
      body += `<g transform="translate(${x} ${y}) scale(${s})">${inner(item.svg)}</g></g>`;
    }),
  );
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">${body}</svg>`;
  const png = new Resvg(svg, { fitTo: { mode: 'original' } }).render().asPng();
  writeFileSync(join(sheetDir, `${name}.png`), png);
}

const bySpecies = SPECIES.map((s) => all.filter((a) => a.species === s.key));
// Detail sheets: 4 species per sheet (rows) × 6 variants.
for (let i = 0; i < bySpecies.length; i += 4) {
  sheet(
    `detail-${String(i / 4 + 1).padStart(2, '0')}`,
    bySpecies.slice(i, i + 4),
    150,
    '#F6F3EE',
    '#FFE7C7',
  );
}
// Every avatar small, light and dark bubbles (legibility at 32-48 px).
sheet('all-48-light', bySpecies, 48, '#FFFFFF', '#E8EEFF');
sheet('all-48-dark', bySpecies, 48, '#14161F', '#2A2F45');
sheet('all-32-light', bySpecies, 32, '#FFFFFF', '#FFE9D6');
// One row per variant (kids, teens …) to compare a family group at a glance.
for (const v of VARIANTS)
  sheet(
    `variant-${v}`,
    [all.filter((a) => a.v === v).slice(0, 11), all.filter((a) => a.v === v).slice(11)],
    96,
    '#FFFFFF',
    '#EAF3FF',
  );

const bytes = all.reduce((n, a) => n + a.svg.length, 0);
console.log(
  `clan: ${all.length} avatars, ${(bytes / 1024).toFixed(0)} KB of SVG, sheets in assets/clan/_sheets`,
);
